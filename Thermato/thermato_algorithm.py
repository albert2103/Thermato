            # ── 2. Classified raster with PAL palette ──
            lyr_cls = QgsRasterLayer(out_cls, 'THERMATO - Risk Classified')
            if lyr_cls.isValid():
                # Build QgsPalettedRasterRenderer classes
                pal_classes = []
                for cls_val in all_cls_vals:
                    rgba = actual_colors.get(cls_val, (128, 128, 128, 255))
