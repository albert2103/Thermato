    def _cleanup_temp_files(self, resampled_paths, feedback):
        import shutil
        for name, path in resampled_paths.items():
            if name != 'lst' and os.path.exists(path):
                temp_dir = os.path.dirname(path)
                if 'thermato_' in temp_dir:
                    try:
                        shutil.rmtree(temp_dir)
                        feedback.pushInfo(
                            f'  Temp cleaned: {os.path.basename(temp_dir)}'
                        )
                        break
                    except Exception:
                        pass
